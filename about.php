        <legend>&#127875; Trick-or-Treat News Plugin</legend>
        <div style="overflow: hidden; padding: 10px;">
            Puts trick-or-treaters on your LED matrix as a "Spooky News" broadcast: their name, a TREAT or TRICK
            verdict, and a photo or costume picture, with a scrolling ticker underneath.<br /><br />
            Enter names from any phone on your Wi-Fi using the <strong>Door page</strong> (link on the setup page) —
            no cloud account or port forwarding needed. Optionally also polls a cloud submissions service.<br /><br />
            Halloween fork of
            <a href="https://github.com/jjarboe01/fpp-plugin-naughtynice" target="_blank">fpp-plugin-naughtynice</a>
            by Joseph Jarboe — all of the FPP plumbing (zone provisioning, overlay display, daemon lifecycle) comes from there.
